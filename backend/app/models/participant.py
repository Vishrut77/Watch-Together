from datetime import datetime

from sqlalchemy import JSON, DateTime, ForeignKey, Index, String
from sqlalchemy.orm import Mapped, mapped_column

from app.database.database import Base
from app.utils.helpers import utcnow


class Participant(Base):
    __tablename__ = "participants"
    __table_args__ = (Index("ix_participant_room_client", "room_id", "client_id", unique=True),)

    id: Mapped[str] = mapped_column(String(32), primary_key=True)
    room_id: Mapped[str] = mapped_column(ForeignKey("rooms.id"), index=True)
    nickname: Mapped[str] = mapped_column(String(24))
    # Random secret generated by the browser. Lets a device resume its seat and makes bans stick.
    client_id: Mapped[str] = mapped_column(String(64))
    role: Mapped[str] = mapped_column(String(12), default="participant")  # owner | cohost | participant
    permissions: Mapped[list] = mapped_column(JSON, default=list)  # only meaningful for cohosts
    status: Mapped[str] = mapped_column(String(12), default="active")  # active | left | kicked | banned
    joined_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    last_seen: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True, default=utcnow)
    left_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
